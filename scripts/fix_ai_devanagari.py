import os

GU_DIR = r"c:\Users\Rahul\Videos\My projects\RtechLab\DIGITAL\AI_ESSENTIALS\07_SOURCE_FILES\Gujarati"

def replace_in_file(filename, replacements):
    path = os.path.join(GU_DIR, filename)
    with open(path, "r", encoding="utf-8") as f:
        content = f.read()
    orig = content
    for target, repl in replacements:
        if target in content:
            content = content.replace(target, repl)
        else:
            print(f"WARNING: Target not found in {filename}: {target[:30]}...")
    if content != orig:
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"Updated {filename}")
    else:
        print(f"No changes in {filename}")

