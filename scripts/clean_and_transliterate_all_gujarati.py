# Transliterate any remaining Devanagari character to Gujarati Unicode
def devanagari_to_gujarati(text):
    res = []
    for ch in text:
        code = ord(ch)
        if 0x0900 <= code <= 0x097F:
            if code == 0x0964 or code == 0x0965: # danda
                res.append('.')
            else:
                gu_code = code + 0x0180
                # ensure valid Gujarati range 0x0A80-0x0AFF
                if 0x0A80 <= gu_code <= 0x0AFF:
                    res.append(chr(gu_code))
                else:
                    res.append(ch)
        else:
            res.append(ch)
    return ''.join(res)

