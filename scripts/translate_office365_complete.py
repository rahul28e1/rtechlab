for fpath in glob.glob(os.path.join(o365_dir, "*.typ")):
    fname = os.path.basename(fpath)
    with open(fpath, "r", encoding="utf-8") as f:
        content = f.read()
    orig = content
    
    # 1. Apply general typo and hinge replacements
    for target, repl in general_replacements:
        content = content.replace(target, repl)
        
    # 2. Apply file specific Devanagari replacements
    if fname in file_specific:
        for target, repl in file_specific[fname]:
            content = content.replace(target, repl)
            
    if content != orig:
        with open(fpath, "w", encoding="utf-8") as f:
            f.write(content)
        modified_files += 1
        print(f"Cleaned {fname}")

